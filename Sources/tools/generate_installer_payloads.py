"""Embed the existing, pinned patch recipes; never embed original EXE files."""
from pathlib import Path
import argparse,json
from patch_catalog import load_catalog

ROOT=Path(__file__).resolve().parents[1]

def main(patch_directory=None,destination=None):
    catalog=load_catalog(patch_directory) if patch_directory else load_catalog()
    files=catalog['current']['files']
    items=[(1,m) for m in files]
    for release in catalog['legacy']:
        if 'same_as' not in release:
            items.extend((release['compatibility_id'],m) for m in release['files'])
    blob=bytearray();spans={};definitions=[];manifest_names=[];by_object={}
    def span(data):
        if not data:return '{0,0}'
        if data not in spans:spans[data]=len(blob);blob.extend(data)
        return '{payload_blob+'+str(spans[data])+','+str(len(data))+'}'
    def pointer(data):
        if data not in spans:spans[data]=len(blob);blob.extend(data)
        return 'payload_blob+'+str(spans[data])
    def raw(value):return bytes.fromhex(value or '')
    for index,(release,m) in enumerate(items):
        name='manifest_'+str(index);manifest_names.append(name)
        by_object[id(m)]=name
        changes=[]
        for c in m.get('changes',[]):
            changes.append('{'+str(c['offset'])+','+span(raw(c['before']))+','+span(raw(c['after']))+'}')
        replacements=[]
        for r in m.get('replacements',[]):replacements.append('{'+span(r['before'].encode())+','+span(r['after'].encode())+'}')
        if changes:definitions.append('static const PrChange '+name+'_changes[]={'+','.join(changes)+'};')
        if replacements:definitions.append('static const PrReplacement '+name+'_replacements[]={'+','.join(replacements)+'};')
        fields=dict(filename=json.dumps(m['filename']),kind=str({'pe':0,'text':1,'new':2}[m['kind']]),release=str(release),
                    original_size=str(m['original_size']),patched_size=str(m['patched_size']),
                    original_hash=pointer(raw(m['original_sha256'])) if m.get('original_sha256') else '0',
                    patched_hash=pointer(raw(m['patched_sha256'])),
                    changes=name+'_changes' if changes else '0',change_count=str(len(changes)),
                    replacements=name+'_replacements' if replacements else '0',replacement_count=str(len(replacements)),
                    append=span(raw(m.get('append_hex'))),contents=span(raw(m.get('contents_hex'))))
        definitions.append('static const PrManifest '+name+'={'+','.join('.'+k+'='+v for k,v in fields.items())+'};')
    receipt=catalog['receipt_bytes'];fingerprint=catalog['receipt']['payload']
    definitions.append('const unsigned char pr_receipt[]={'+','.join(str(b) for b in receipt)+'};')
    definitions.append('const size_t pr_receipt_size=sizeof pr_receipt;')
    definitions.append('const char pr_project_version[]='+json.dumps(catalog['current']['version'])+';')
    definitions.append('const PrManifest *const pr_current[]={'+','.join('&'+by_object[id(m)] for m in files)+'};')
    definitions.append('const PrManifest *const pr_known[]={'+','.join('&'+name for name in manifest_names)+'};')
    definitions.append('const size_t pr_known_count=sizeof pr_known/sizeof pr_known[0];')
    legacy_rows=[]
    for release in catalog['legacy']:
        name='legacy_'+str(release['compatibility_id'])
        definitions.append('static const PrManifest *const '+name+'_files[]={'+','.join('&'+by_object[id(m)] for m in release['files'])+'};')
        legacy_rows.append('{'+str(release['compatibility_id'])+','+str(int(release['preview']))+','+
                           json.dumps(release['version'])+','+name+'_files,'+str(len(release['files']))+','+span(release['receipt_bytes'])+'}')
    definitions.append('const PrLegacyRelease pr_legacy_releases[]={'+','.join(legacy_rows)+'};')
    definitions.append('const size_t pr_legacy_release_count=sizeof pr_legacy_releases/sizeof pr_legacy_releases[0];')
    definitions.append('const char *const pr_paths[]={"wallpaper32.exe","wallpaper64.exe","ui/dist/scripts/scripts.js",'
                       '"PlaylistResume32.dll","PlaylistResume64.dll","PiPlaylistResume32.dll","PiPlaylistResume64.dll"};')
    rows=[','.join('0x%02x'%b for b in blob[i:i+24]) for i in range(0,len(blob),24)]
    text='/* Generated by tools/generate_installer_payloads.py. */\n#include "installer_core.h"\nstatic const unsigned char payload_blob[]={\n'+',\n'.join(rows)+'\n};\n'+'\n'.join(definitions)+'\n'
    Path(destination or ROOT/'installer/payloads.c').write_text(text)
    print('Embedded recipes:',len(items),'deduplicated bytes:',len(blob),'receipt:',fingerprint)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog',type=Path);parser.add_argument('--output',type=Path)
    arguments=parser.parse_args();main(arguments.catalog,arguments.output)
